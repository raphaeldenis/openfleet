import { describe, expect, it } from 'vitest';
import { isPublicAddress } from './providerAddress.js';

describe('which addresses a provider may be reached at', () => {
  it.each([
    ['a public IPv4 address', '104.192.136.30'],
    ['the first public address after the 172.16.0.0/12 range', '172.32.0.1'],
    ['the last public address before the 172.16.0.0/12 range', '172.15.255.255'],
    ['the last public address before shared address space', '100.63.255.255'],
    ['the first public address after shared address space', '100.128.0.0'],
    ['a public address between the 192.0.0.0/24 and 192.0.2.0/24 ranges', '192.0.1.1'],
    ['the first public address after 192.0.2.0/24', '192.0.3.1'],
    ['the last public address before benchmark 198.18/15', '198.17.255.255'],
    ['the first public address after benchmark 198.18/15', '198.20.0.0'],
    ['the last public address before 198.51.100.0/24', '198.51.99.255'],
    ['the first public address after 198.51.100.0/24', '198.51.101.0'],
    ['the last public address before 203.0.113.0/24', '203.0.112.255'],
    ['the first public address after 203.0.113.0/24', '203.0.114.0'],
    ['the last public address before multicast', '223.255.255.255'],
    ['the first address after the 0.0.0.0/8 range', '1.0.0.0'],
    ['the last address before loopback', '126.255.255.255'],
    ['a public IPv6 address', '2606:4700:4700::1111'],
    ['a public IPv6 address under 2001:', '2001:4860:4860::8888'],
    ['the first IPv6 address after the 2001::/23 protocol assignments', '2001:200::1'],
    ['the IPv6 address just below the documentation range 2001:db8::/32', '2001:db7::1'],
    ['the IPv6 address just above the documentation range 2001:db8::/32', '2001:db9::1'],
    ['the first IPv6 address after 6to4', '2003::1'],
    ['the first IPv6 address after the 3fff::/20 documentation range', '3fff:1000::1'],
    ['the start of global unicast', '2000::1'],
    ['the end of global unicast', '3ffe:ffff::1'],
    ['an IPv4-mapped IPv6 form of a public address', '::ffff:104.192.136.30'],
    ['the NAT64 well-known form of a public address', '64:ff9b::104.192.136.30'],
  ])('allows %s', (_label, address) => {
    expect(isPublicAddress(address)).toBe(true);
  });

  it.each([
    ['loopback', '127.0.0.1'],
    ['loopback, last address of its range', '127.255.255.254'],
    ['this network', '0.0.0.0'],
    ['this network, last address of its range', '0.255.255.255'],
    ['private 10/8', '10.1.2.3'],
    ['private 172.16/12', '172.16.0.1'],
    ['private 172.16/12, last address', '172.31.255.255'],
    ['private 192.168/16', '192.168.1.1'],
    ['link-local, the cloud metadata address', '169.254.169.254'],
    ['shared address space 100.64/10', '100.64.0.1'],
    ['shared address space 100.64/10, last address', '100.127.255.255'],
    ['IETF protocol assignments 192.0.0.0/24', '192.0.0.1'],
    ['documentation 192.0.2.0/24', '192.0.2.1'],
    ['6to4 relay anycast 192.88.99.0/24', '192.88.99.1'],
    ['benchmark 198.18/15', '198.19.0.1'],
    ['benchmark 198.18/15, first address', '198.18.0.0'],
    ['documentation 198.51.100.0/24', '198.51.100.1'],
    ['documentation 203.0.113.0/24', '203.0.113.1'],
    ['multicast', '224.0.0.1'],
    ['multicast, last address', '239.255.255.255'],
    ['reserved 240/4, first address', '240.0.0.1'],
    ['reserved, broadcast', '255.255.255.255'],
    ['IPv6 loopback', '::1'],
    ['IPv6 unspecified', '::'],
    ['IPv6 unique local', 'fd00::1'],
    ['IPv6 unique local fc00::/7', 'fc00::1'],
    ['IPv6 link-local', 'fe80::1'],
    ['IPv6 site-local, deprecated', 'fec0::1'],
    ['IPv6 multicast', 'ff02::1'],
    ['IPv6 outside global unicast, just below 2000::/3', '1fff:ffff::1'],
    ['IPv6 outside global unicast, just above 2000::/3', '4000::1'],
    ['IPv6 documentation 2001:db8::/32', '2001:db8::1'],
    ['IPv6 documentation 3fff::/20', '3fff::1'],
    ['IPv6 documentation 3fff::/20, last address', '3fff:fff:ffff:ffff:ffff:ffff:ffff:ffff'],
    ['IPv6 Teredo 2001::/32', '2001::1'],
    ['IPv6 benchmark 2001:2::/48', '2001:2::1'],
    ['IPv6 IETF protocol assignments 2001::/23, last address', '2001:1ff:ffff:ffff:ffff:ffff:ffff:ffff'],
    ['IPv6 ORCHID 2001:10::/28', '2001:10::1'],
    ['IPv4-compatible IPv6 of loopback', '::127.0.0.1'],
    ['IPv4-compatible IPv6 of loopback in hex form', '::7f00:1'],
    ['IPv4-compatible IPv6 of a public address, deprecated and routed nowhere', '::104.192.136.30'],
    ['IPv4-mapped IPv6 of a private address', '::ffff:10.0.0.1'],
    ['IPv4-mapped IPv6 of loopback in dotted form', '::ffff:127.0.0.1'],
    ['IPv4-mapped IPv6 of loopback in hex form', '::ffff:7f00:1'],
    ['IPv4-mapped IPv6 of a documentation address', '::ffff:192.0.2.1'],
    ['NAT64 well-known form of a private address', '64:ff9b::a00:1'],
    ['NAT64 well-known form of loopback', '64:ff9b::127.0.0.1'],
    ['NAT64 local-use form', '64:ff9b:1::a00:1'],
    ['NAT64 local-use form of a public address', '64:ff9b:1::104.192.136.30'],
    ['6to4 form', '2002:a00:1::'],
    ['6to4 form of a public address', '2002:68c0:881e::1'],
    ['text that is not an address', 'acme.atlassian.net'],
    ['an empty text', ''],
    ['an IPv6 address with a zone', '2606:4700:4700::1111%eth0'],
    ['an IPv4 address with a port', '104.192.136.30:443'],
  ])('refuses %s', (_label, address) => {
    expect(isPublicAddress(address)).toBe(false);
  });
});
